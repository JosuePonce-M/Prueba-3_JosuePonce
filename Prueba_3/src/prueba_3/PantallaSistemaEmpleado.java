private Empleado buscarPorCodigo(String codigo) {
    for (Empleado e : empleados) {
        if (e.getCodigo().equalsIgnoreCase(codigo)) {
            return e;
        }
    }
    return null;
}

private String tipoDe(Empleado e) {
    if (e instanceof EmpleadoAdministrativo) {
        return "Administrativo";
    }
    return "Por horas";
}
